def _category_for(code: str) -> str:
    return 'Специалитет' if code[0] == '5' else 'Бакалавриат'


def main() -> None:
    print('=== Sync programs (uni-dubna.ru, 31) ===')
    with SessionLocal() as db:
        features = {f.code: f for f in db.scalars(select(Feature)).all()}
        existing = {d.name: d for d in db.scalars(select(Direction)).all()}

        # 1) деактивируем всё — активными станут только программы из списка
        for d in existing.values():
            d.is_active = False
        db.flush()

        # 2) создаём/обновляем 31 программу
        for idx, (name, code, years, ege, skills) in enumerate(PROGRAMS):
            d = existing.get(name)
            if d is None:
                d = Direction(
                    name=name,
                    fgos_code=code,
                    description=PROGRAM_DESCRIPTIONS.get(name, ''),
                    category=_category_for(code),
                    study_years=years,
                    ege_typical=ege,
                    sort_order=idx,
                    is_active=True,
                )
                db.add(d)
                db.flush()
                existing[name] = d
                print(f'  + {name} ({code})')
            else:
                d.fgos_code = code
                d.description = PROGRAM_DESCRIPTIONS.get(name, d.description)
                d.category = _category_for(code)
                d.study_years = years
                d.ege_typical = ege
                d.sort_order = idx
                d.is_active = True
            # навыки
            for skill_code in skills:
                feature = features.get(skill_code)
                if feature is not None and feature not in d.features:
                    d.features.append(feature)

        db.commit()
        active = db.scalar(select(Direction).where(Direction.is_active.is_(True)))
        active_count = len(db.scalars(select(Direction).where(Direction.is_active.is_(True))).all())
        print(f'  активных программ: {active_count}')
    print('=== Sync done ===')


if __name__ == '__main__':
    main()